//! Go's public API over cgo. C retains only malloc'd contexts containing
//! runtime/cgo.Handle integers; no Go pointer crosses a callback lifetime.
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;
use std::path::Path;

use codegen_shared::ir::{Api, Class, ClassKind, Constructor, EventGroup, Method, Param, TypeRef};
use codegen_shared::naming::*;
