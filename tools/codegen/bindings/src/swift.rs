/// Swift expression converting the C value at `access` to the public field type.
fn swift_field_from_raw(ty: &TypeRef, access: &str) -> String {
    match ty {
        TypeRef::String | TypeRef::CString => format!("{access}.map {{ String(cString: $0) }}"),
        TypeRef::Optional { inner } => match inner.as_ref() {
            TypeRef::String | TypeRef::CString => {
                format!("{access}.map {{ String(cString: $0) }}")
            }
            TypeRef::Struct { name, .. } => {
                format!("{access}.map {{ {name}(raw: $0.pointee) }}")
            }
            TypeRef::Object { name, .. } => {
                format!("nativeapiOwned({access}) {{ {name}(nativeHandle: $0) }}")
            }
            other => swift_field_from_raw(other, access),
        },
        TypeRef::Enum { name, .. } => format!("{name}(raw: {access})"),
        TypeRef::Struct { name, .. } => format!("{name}(raw: {access})"),
        TypeRef::Object { name, .. } => {
            format!("nativeapiOwned({access}) {{ {name}(nativeHandle: $0) }}")
        }
        TypeRef::Vector { element } if matches!(element.as_ref(), TypeRef::String) => {
            format!("nativeapiStringList({access})")
        }
        TypeRef::Map { .. } => format!("nativeapiStringMap({access})"),
        TypeRef::Callback { .. } => "nil".to_string(),
        _ => access.to_string(),
    }
}

fn swift_field_to_raw(
    out: &mut String,
    api: &Api,
    ty: &TypeRef,
    public: &str,
    raw: &str,
    indent: &str,
) {
    match ty {
        TypeRef::String | TypeRef::CString => {
            writeln!(
                out,
                "{indent}raw.{raw} = self.{public}.map {{ strdup($0) }}"
            )
            .unwrap();
        }
        TypeRef::Optional { inner } => match inner.as_ref() {
            TypeRef::String | TypeRef::CString => {
                writeln!(
                    out,
                    "{indent}raw.{raw} = self.{public}.map {{ strdup($0) }}"
                )
                .unwrap();
            }
            TypeRef::Struct { name, .. } => {
                writeln!(out, "{indent}if let value = self.{public} {{").unwrap();
                writeln!(
                    out,
                    "{indent}  let pointer = UnsafeMutablePointer<{}>.allocate(capacity: 1)",
                    c_type_name(PREFIX, name)
                )
                .unwrap();
                writeln!(out, "{indent}  pointer.initialize(to: value.toRaw())").unwrap();
                writeln!(out, "{indent}  raw.{raw} = pointer").unwrap();
                writeln!(out, "{indent}}} else {{").unwrap();
                writeln!(out, "{indent}  raw.{raw} = nil").unwrap();
                writeln!(out, "{indent}}}").unwrap();
            }
            TypeRef::Callback { params } => {
                swift_callback_struct_field(out, params, public, raw, indent);
            }
            other => swift_field_to_raw(out, api, other, public, raw, indent),
        },
        TypeRef::Struct { name, .. } => {
            writeln!(out, "{indent}raw.{raw} = self.{public}.toRaw()").unwrap();
            let _ = name;
        }
        TypeRef::Enum { .. } => {
            writeln!(out, "{indent}raw.{raw} = self.{public}.raw").unwrap();
        }
        TypeRef::Object { .. } => {
            writeln!(out, "{indent}raw.{raw} = self.{public}?.nativeHandle ?? 0").unwrap();
        }
        TypeRef::Vector { element } if matches!(element.as_ref(), TypeRef::String) => {
            writeln!(out, "{indent}if !self.{public}.isEmpty {{").unwrap();
            writeln!(
                out,
                "{indent}  let pointers = self.{public}.map {{ strdup($0) }}"
            )
            .unwrap();
            writeln!(out, "{indent}  raw.{raw}.count = numericCast(pointers.count)").unwrap();
            writeln!(
                out,
                "{indent}  raw.{raw}.items = UnsafeMutablePointer<UnsafeMutablePointer<CChar>?>.allocate(capacity: pointers.count)"
            )
            .unwrap();
            writeln!(
                out,
                "{indent}  for (index, pointer) in pointers.enumerated() {{ raw.{raw}.items[index] = pointer }}"
            )
            .unwrap();
            writeln!(out, "{indent}}}").unwrap();
        }
        TypeRef::Map { .. } => {
            writeln!(out, "{indent}if !self.{public}.isEmpty {{").unwrap();
            writeln!(
                out,
                "{indent}  let keys = self.{public}.keys.map {{ strdup($0) }}"
            )
            .unwrap();
            writeln!(
                out,
                "{indent}  let values = self.{public}.values.map {{ strdup($0) }}"
            )
            .unwrap();
            writeln!(out, "{indent}  raw.{raw}.count = numericCast(keys.count)").unwrap();
            writeln!(
                out,
                "{indent}  raw.{raw}.keys = UnsafeMutablePointer<UnsafeMutablePointer<CChar>?>.allocate(capacity: keys.count)"
            )
            .unwrap();
            writeln!(
                out,
                "{indent}  raw.{raw}.values = UnsafeMutablePointer<UnsafeMutablePointer<CChar>?>.allocate(capacity: values.count)"
            )
            .unwrap();
            writeln!(
                out,
                "{indent}  for (index, pointer) in keys.enumerated() {{ raw.{raw}.keys[index] = pointer }}"
            )
            .unwrap();
            writeln!(
                out,
                "{indent}  for (index, pointer) in values.enumerated() {{ raw.{raw}.values[index] = pointer }}"
            )
            .unwrap();
            writeln!(out, "{indent}}}").unwrap();
        }
        TypeRef::Callback { params } => {
            swift_callback_struct_field(out, params, public, raw, indent);
        }
        _ => {
            writeln!(out, "{indent}raw.{raw} = self.{public}").unwrap();
        }
    }
}

fn swift_callback_struct_field(
    out: &mut String,
    params: &[TypeRef],
    public: &str,
    raw: &str,
    indent: &str,
) {
    let note = format!("{indent}  ");
    let arity = params.len();
    let generics = swift_box_generics(params);
    writeln!(out, "{indent}if let callback = self.{public} {{").unwrap();
    writeln!(
        out,
        "{note}let context = Unmanaged.passRetained(CallbackBox{arity}{generics}(callback)).toOpaque()"
    )
    .unwrap();
    writeln!(
        out,
        "{note}let trampoline: @convention(c) ({}) -> Void = {{ {} in",
        callback_c_field_types(params),
        callback_c_field_names(params).join(", ")
    )
    .unwrap();
    writeln!(
        out,
        "{note}  guard let userData = {0} else {{ return }}",
        callback_c_field_names(params).last().unwrap()
    )
    .unwrap();
    let values: Vec<String> = params
        .iter()
        .enumerate()
        .map(|(index, ty)| swift_callback_arg_value(ty, &format!("arg{index}")).1)
        .collect();
    writeln!(
        out,
        "{note}  Unmanaged<CallbackBox{arity}{generics}>.fromOpaque(userData).takeUnretainedValue().body({})",
        values.join(", ")
    )
    .unwrap();
    writeln!(out, "{note}}}").unwrap();
    writeln!(out, "{note}raw.{raw} = trampoline").unwrap();
    writeln!(out, "{note}raw.{} = context", c_user_data_param(raw)).unwrap();
    writeln!(
        out,
        "{note}raw.{} = nativeapiReleaseUserData",
        c_release_user_data_param(raw)
    )
    .unwrap();
    writeln!(out, "{indent}}}").unwrap();
}

fn callback_c_field_types(params: &[TypeRef]) -> String {
    let mut types: Vec<String> = params.iter().map(swift_c_callback_arg_type).collect();
    types.push("UnsafeMutableRawPointer?".to_string());
    types.join(", ")
}

fn callback_c_field_names(params: &[TypeRef]) -> Vec<String> {
    let mut names: Vec<String> = (0..params.len())
        .map(|index| format!("arg{index}"))
        .collect();
    names.push("userData".to_string());
    names
}

fn swift_field_release(out: &mut String, api: &Api, ty: &TypeRef, raw: &str, indent: &str) {
    match ty {
        TypeRef::String | TypeRef::CString => {
            writeln!(out, "{indent}free(raw.{raw})").unwrap();
            writeln!(out, "{indent}raw.{raw} = nil").unwrap();
        }
        TypeRef::Optional { inner } => match inner.as_ref() {
            TypeRef::String | TypeRef::CString => {
                writeln!(out, "{indent}free(raw.{raw})").unwrap();
                writeln!(out, "{indent}raw.{raw} = nil").unwrap();
            }
            TypeRef::Struct { name, .. } => {
                writeln!(out, "{indent}if let pointer = raw.{raw} {{").unwrap();
                if struct_allocates_named(api, name) {
                    writeln!(out, "{indent}  {name}.releaseRaw(&pointer.pointee)").unwrap();
                }
                writeln!(out, "{indent}  pointer.deinitialize(count: 1)").unwrap();
                writeln!(out, "{indent}  pointer.deallocate()").unwrap();
                writeln!(out, "{indent}}}").unwrap();
                writeln!(out, "{indent}raw.{raw} = nil").unwrap();
            }
            other => swift_field_release(out, api, other, raw, indent),
        },
        TypeRef::Struct { name, .. } => {
            if struct_allocates_named(api, name) {
                writeln!(out, "{indent}{name}.releaseRaw(&raw.{raw})").unwrap();
            }
        }
        TypeRef::Vector { element } if matches!(element.as_ref(), TypeRef::String) => {
            writeln!(out, "{indent}if let items = raw.{raw}.items {{").unwrap();
            writeln!(out, "{indent}  for index in 0..<Int(raw.{raw}.count) {{").unwrap();
            writeln!(out, "{indent}    free(items[index])").unwrap();
            writeln!(out, "{indent}  }}").unwrap();
            writeln!(out, "{indent}  items.deallocate()").unwrap();
            writeln!(out, "{indent}}}").unwrap();
            writeln!(out, "{indent}raw.{raw} = native_string_list_t()").unwrap();
        }
        TypeRef::Map { .. } => {
            writeln!(
                out,
                "{indent}if let keys = raw.{raw}.keys, let values = raw.{raw}.values {{"
            )
            .unwrap();
            writeln!(out, "{indent}  for index in 0..<Int(raw.{raw}.count) {{").unwrap();
            writeln!(out, "{indent}    free(keys[index])").unwrap();
            writeln!(out, "{indent}    free(values[index])").unwrap();
            writeln!(out, "{indent}  }}").unwrap();
            writeln!(out, "{indent}  keys.deallocate()").unwrap();
            writeln!(out, "{indent}  values.deallocate()").unwrap();
            writeln!(out, "{indent}}}").unwrap();
            writeln!(out, "{indent}raw.{raw} = native_string_map_t()").unwrap();
        }
        _ => {}
    }
}

/// Whether `toRaw()` allocates memory that `releaseRaw` must free.
fn struct_allocates(api: &Api, item: &Struct) -> bool {
    item.fields.iter().any(|field| ty_allocates(api, &field.ty))
}

fn ty_allocates(api: &Api, ty: &TypeRef) -> bool {
    match ty {
        TypeRef::String | TypeRef::CString | TypeRef::Vector { .. } | TypeRef::Map { .. } => true,
        TypeRef::Optional { inner } => ty_allocates(api, inner),
        TypeRef::Struct { name, .. } => struct_allocates_named(api, name),
        _ => false,
    }
}

fn struct_allocates_named(api: &Api, name: &str) -> bool {
    api.headers
        .iter()
        .flat_map(|header| header.structs.iter())
        .find(|item| item.name == name)
        .is_some_and(|item| struct_allocates(api, item))
}

fn struct_owns_memory(api: &Api, name: &str) -> bool {
    api.headers
        .iter()
        .flat_map(|header| header.structs.iter())
        .find(|item| item.name == name)
        .is_some_and(struct_has_owned_fields)
}

