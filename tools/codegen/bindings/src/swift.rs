/// Whether a derived class's constructor overrides one inherited from a base.
fn constructor_overrides(api: &Api, class: &Class, ctor: &Constructor) -> bool {
    ancestor_constructors(api, class)
        .into_iter()
        .any(|(_, ancestor)| {
            ancestor.params.len() == ctor.params.len()
                && ancestor
                    .params
                    .iter()
                    .zip(&ctor.params)
                    .all(|(left, right)| {
                        swift_ident(&left.name.to_lower_camel_case())
                            == swift_ident(&right.name.to_lower_camel_case())
                            && left.ty == right.ty
                    })
        })
}

