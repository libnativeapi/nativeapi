struct MethodShape {
    name: String,
    property: bool,
    is_static: bool,
}

fn method_shape(class: &Class, method: &Method) -> MethodShape {
    let property = is_binding_accessor(class, method) && method.params.is_empty();
    MethodShape {
        name: swift_method_name(class, method),
        property,
        is_static: method.is_static && class.is_instance(),
    }
}

fn method_declaration(_class: &Class, method: &Method, shape: &MethodShape) -> String {
    let name = swift_ident(&shape.name);
    if shape.property {
        return format!("var {name}: {}", swift_public_type(&method.return_type));
    }
    let keyword = if shape.is_static {
        "static func"
    } else {
        "func"
    };
    format!(
        "{keyword} {name}({}) -> {}",
        swift_params(&method.params),
        swift_public_type(&method.return_type)
    )
}

