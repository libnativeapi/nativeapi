//! Swift's public API over the generated C ABI.
//!
//! Handles become ARC-managed references: `dispose()` releases immediately on
//! the UI thread, while `deinit` hands the handle to `native_handle_finalize`,
//! which hops to the UI thread first. Callback closures travel through a
//! retained `CallbackBox` released by the C ABI's `release_user_data` hook.
use std::fmt::Write;
use std::path::Path;

use heck::{ToLowerCamelCase, ToShoutySnakeCase, ToSnakeCase, ToUpperCamelCase};

use codegen_shared::ir::{
    Api, Class, Constructor, Enum, EventGroup, Header, Method, Param, Struct, TypeRef,
};
use codegen_shared::naming::{
    ancestor_constructors, c_add_listener_symbol, c_constructor_symbol, c_enum_variant,
    c_event_variant, c_event_variant_field, c_free_symbol, c_invalid_handle_macro, c_list_field,
    c_list_release_symbol, c_method_symbol, c_native_object_symbol, c_release_user_data_param,
    c_remove_listener_symbol, c_type_name, c_user_data_param, constructor_suffix,
    is_binding_accessor, struct_has_owned_fields, swift_method_name, TypeOrigins, STRING_FREE_FN,
    STRING_LIST_FREE_FN, STRING_LIST_TYPE, STRING_MAP_FREE_FN, STRING_MAP_TYPE,
};
use codegen_shared::GeneratedFile;

const PREFIX: &str = "native_";
const BANNER: &str = "// AUTO-GENERATED. DO NOT EDIT.\n// Code generated by ./codegen. DO NOT EDIT.\n// Any manual changes WILL BE LOST when this file is regenerated.\n\n";

pub fn generate(
    api: &Api,
    header: &Header,
    origins: &TypeOrigins,
    swift_out: &Path,
    prefix: &str,
    subdir: Option<&Path>,
) -> GeneratedFile {
    let file_name = format!("{}.swift", header.stem.to_upper_camel_case());
    // Swift mirrors the source tree but in its own casing: `src/foundation/`
    // becomes `Sources/NativeAPI/Foundation/`.
    let out_path = match subdir {
        Some(dir) => {
            let mut path = swift_out.to_path_buf();
            for part in dir.components() {
                path.push(part.as_os_str().to_string_lossy().to_upper_camel_case());
            }
            path.join(&file_name)
        }
        None => swift_out.join(&file_name),
    };
    GeneratedFile {
        path: out_path,
        contents: generate_swift(api, header, origins, prefix),
    }
}

/// Swift has one namespace per module, so anything shared between generated
/// files is declared exactly once here.
pub fn generate_support(api: &Api, swift_out: &Path) -> GeneratedFile {
    let mut out = String::new();
    write!(out, "{BANNER}").unwrap();
    writeln!(out, "import CNativeAPI").unwrap();
    writeln!(out, "import Foundation").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "/// Identifies one registered event listener.").unwrap();
    writeln!(out, "public typealias ListenerId = native_listener_id_t").unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "/// Releases the callback context the bindings hand to C as `user_data`."
    )
    .unwrap();
    writeln!(
        out,
        "let nativeapiReleaseUserData: native_release_user_data_t = {{ userData in"
    )
    .unwrap();
    writeln!(out, "  guard let userData else {{ return }}").unwrap();
    writeln!(out, "  Unmanaged<AnyObject>.fromOpaque(userData).release()").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "/// Turns a borrowed handle into an owned reference, or nil when invalid."
    )
    .unwrap();
    writeln!(
        out,
        "func nativeapiOwned<T>(_ handle: UInt64, _ make: (UInt64) -> T) -> T? {{"
    )
    .unwrap();
    writeln!(out, "  let retained = native_handle_retain(handle)").unwrap();
    writeln!(out, "  return retained == 0 ? nil : make(retained)").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "/// Copies a native string list into Swift strings.").unwrap();
    writeln!(
        out,
        "func nativeapiStringList(_ raw: native_string_list_t) -> [String] {{"
    )
    .unwrap();
    writeln!(out, "  guard let items = raw.items else {{ return [] }}").unwrap();
    writeln!(out, "  return (0..<Int(raw.count)).compactMap {{ index in").unwrap();
    writeln!(out, "    items[index].map {{ String(cString: $0) }}").unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "/// Copies a native string map into a Swift dictionary."
    )
    .unwrap();
    writeln!(
        out,
        "func nativeapiStringMap(_ raw: native_string_map_t) -> [String: String] {{"
    )
    .unwrap();
    writeln!(
        out,
        "  guard let keys = raw.keys, let values = raw.values else {{ return [:] }}"
    )
    .unwrap();
    writeln!(out, "  var result: [String: String] = [:]").unwrap();
    writeln!(out, "  for index in 0..<Int(raw.count) {{").unwrap();
    writeln!(out, "    guard let key = keys[index] else {{ continue }}").unwrap();
    writeln!(
        out,
        "    result[String(cString: key)] = values[index].map {{ String(cString: $0) }} ?? \"\""
    )
    .unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out, "  return result").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    let mut arities: Vec<usize> = api.headers.iter().flat_map(callback_arities).collect();
    // Every listener registration goes through a one-argument box.
    if api
        .headers
        .iter()
        .any(|header| header.classes.iter().any(|class| class.event.is_some()))
    {
        arities.push(1);
    }
    arities.sort_unstable();
    arities.dedup();
    for arity in arities {
        generate_swift_callback_box(&mut out, arity);
    }

    GeneratedFile {
        path: swift_out.join("Support.swift"),
        contents: trim_trailing_newlines(out),
    }
}

/// Generated modules end with exactly one newline, not a blank line.
fn trim_trailing_newlines(mut text: String) -> String {
    while text.ends_with('\n') {
        text.pop();
    }
    text.push('\n');
    text
}

fn generate_swift(api: &Api, header: &Header, origins: &TypeOrigins, prefix: &str) -> String {
    let mut out = String::new();
    write!(out, "{BANNER}").unwrap();
    writeln!(out, "import CNativeAPI").unwrap();
    writeln!(out, "import Foundation").unwrap();
    writeln!(out).unwrap();

    for alias in &header.aliases {
        if origins.get(&alias.name).map(String::as_str) != Some(header.stem.as_str()) {
            continue;
        }
        writeln!(
            out,
            "public typealias {} = {}",
            alias.name,
            swift_public_type(&alias.underlying)
        )
        .unwrap();
        writeln!(out).unwrap();
    }

    for item in &header.enums {
        generate_swift_enum(&mut out, item, prefix);
    }

    for item in &header.structs {
        generate_swift_struct(&mut out, api, item, prefix);
    }

    for group in &header.events {
        generate_swift_event(&mut out, group, prefix);
    }

    for class in &header.classes {
        if class.is_instance() {
            generate_swift_handle_class(&mut out, api, class, prefix);
        } else {
            // Singletons surface as `.shared` instances rather than static
            // namespaces so they can adopt protocols and be swapped in tests.
            writeln!(out, "public final class {}: Sendable {{", class.name).unwrap();
            writeln!(
                out,
                "  /// The shared instance backed by the native singleton."
            )
            .unwrap();
            writeln!(out, "  public static let shared = {}()", class.name).unwrap();
            writeln!(out).unwrap();
            writeln!(out, "  private init() {{}}").unwrap();
            writeln!(out).unwrap();
            for method in &class.methods {
                generate_swift_method(&mut out, api, class, method, prefix, "  ", None);
            }
            generate_swift_listener(&mut out, api, class, prefix, "  ");
            writeln!(out, "}}").unwrap();
            writeln!(out).unwrap();
        }
    }

    trim_trailing_newlines(out)
}

