/// What this binding generates for every symbol, keyed like the docs.
pub fn reference(
    api: &Api,
    _origins: &codegen_shared::naming::TypeOrigins,
    _prefix: &str,
) -> crate::reference::Reference {
    use codegen_shared::symbols;
    let mut reference = crate::reference::Reference::default();
    for header in &api.headers {
        for alias in &header.aliases {
            if reference.entries.contains_key(&alias.name) {
                continue;
            }
            reference.insert(
                alias.name.as_str(),
                alias.name.as_str(),
                format!(
                    "typealias {} = {}",
                    alias.name,
                    swift_public_type(&alias.underlying)
                ),
            );
        }
        for item in &header.enums {
            if is_option_set(&item.name) {
                reference.insert(
                    item.name.as_str(),
                    item.name.as_str(),
                    format!("struct {}: OptionSet", item.name),
                );
                for (key, variant) in symbols::enum_variants(item).into_iter().zip(&item.variants) {
                    if variant.value == 0 {
                        continue;
                    }
                    let name = swift_ident(&swift_enum_case(&variant.name));
                    reference.insert(
                        key,
                        name.clone(),
                        format!("static let {name}: {} = {}", item.name, variant.value),
                    );
                }
                continue;
            }
            reference.insert(
                item.name.as_str(),
                item.name.as_str(),
                format!("enum {}: CInt", item.name),
            );
            for (key, variant) in symbols::enum_variants(item).into_iter().zip(&item.variants) {
                let case = swift_ident(&swift_enum_case(&variant.name));
                reference.insert(
                    key,
                    case.clone(),
                    format!("case {case} = {}", variant.value),
                );
            }
        }
        for item in &header.structs {
            reference.insert(
                item.name.as_str(),
                item.name.as_str(),
                format!("struct {}", item.name),
            );
            for (key, field) in symbols::struct_fields(item).into_iter().zip(&item.fields) {
                let name = swift_ident(&field.name.to_lower_camel_case());
                reference.insert(
                    key,
                    name.clone(),
                    format!("var {name}: {}", swift_field_type(&field.ty)),
                );
            }
            let class = struct_pseudo_class(item);
            for (key, method) in symbols::struct_methods(item).into_iter().zip(&item.methods) {
                let shape = method_shape(&class, method);
                reference.insert(
                    key,
                    swift_ident(&shape.name),
                    method_declaration(&class, method, &shape),
                );
            }
            for (key, constant) in symbols::struct_constants(item)
                .into_iter()
                .zip(&item.constants)
            {
                let name = swift_ident(&constant.to_lower_camel_case());
                reference.insert(
                    key,
                    name.clone(),
                    format!("static let {name}: {}", item.name),
                );
            }
        }
        for group in &header.events {
            reference.insert(
                group.name.as_str(),
                group.name.as_str(),
                format!("enum {}", group.name),
            );
            for (key, field) in symbols::event_common_fields(group)
                .into_iter()
                .zip(&group.common)
            {
                let name = swift_ident(&field.name.to_lower_camel_case());
                reference.insert(
                    key,
                    name.clone(),
                    format!("var {name}: {}", swift_event_field_type(&field.ty)),
                );
            }
            for variant in &group.variants {
                let case = swift_ident(&variant.discriminant.to_lower_camel_case());
                let fields: Vec<String> = group
                    .common
                    .iter()
                    .chain(variant.fields.iter())
                    .map(|field| {
                        format!(
                            "{}: {}",
                            swift_ident(&field.name.to_lower_camel_case()),
                            swift_event_field_type(&field.ty)
                        )
                    })
                    .collect();
                reference.insert(
                    variant.name.as_str(),
                    case.clone(),
                    if fields.is_empty() {
                        format!("case {case}")
                    } else {
                        format!("case {case}({})", fields.join(", "))
                    },
                );
                for (key, field) in symbols::event_variant_fields(variant)
                    .into_iter()
                    .zip(&variant.fields)
                {
                    let name = swift_ident(&field.name.to_lower_camel_case());
                    reference.insert(
                        key,
                        name.clone(),
                        format!("var {name}: {}", swift_event_field_type(&field.ty)),
                    );
                }
            }
        }
        for class in &header.classes {
            let declaration = if class.is_singleton() {
                format!("final class {}: Sendable", class.name)
            } else if let Some(base) = &class.base {
                format!("class {}: {}", class.name, base)
            } else {
                format!("class {}", class.name)
            };
            reference.insert(class.name.as_str(), class.name.as_str(), declaration);
            for (key, ctor) in symbols::constructors(class)
                .into_iter()
                .zip(&class.constructors)
            {
                let label = match constructor_suffix(class, ctor) {
                    Some(suffix) => format!("create{}", suffix.to_upper_camel_case()),
                    None => "create".to_string(),
                };
                reference.insert(
                    key,
                    label.clone(),
                    format!(
                        "{}class func {label}({}) -> {}?",
                        if constructor_overrides(api, class, ctor) {
                            "override "
                        } else {
                            ""
                        },
                        swift_params(&ctor.params),
                        class.name
                    ),
                );
            }
            for (key, method) in symbols::class_methods(class)
                .into_iter()
                .zip(&class.methods)
            {
                let shape = method_shape(class, method);
                reference.insert(
                    key,
                    swift_ident(&shape.name),
                    method_declaration(class, method, &shape),
                );
            }
            if let Some(event) = &class.event {
                reference.insert(
                    symbols::listener(class),
                    "addListener",
                    format!(
                        "func addListener(_ callback: @escaping ({event}) -> Void) -> ListenerId\nfunc removeListener(_ listenerId: ListenerId) -> Bool"
                    ),
                );
            }
        }
    }
    reference
}

