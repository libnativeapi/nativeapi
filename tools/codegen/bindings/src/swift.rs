fn generate_swift_handle_class(out: &mut String, api: &Api, class: &Class, prefix: &str) {
    let handle_type = c_type_name(prefix, &class.name);
    let free = c_free_symbol(prefix, &class.name);
    writeln!(out, "/// Owned handle to a native `{}`.", class.name).unwrap();
    if let Some(base) = &class.base {
        writeln!(out, "public class {}: {} {{", class.name, base).unwrap();
        writeln!(out, "  public override func releaseNativeHandle() {{").unwrap();
        writeln!(out, "    {free}(nativeHandle)").unwrap();
        writeln!(out, "  }}").unwrap();
        writeln!(out).unwrap();
    } else {
        writeln!(out, "public class {} {{", class.name).unwrap();
        writeln!(out, "  public let nativeHandle: {handle_type}").unwrap();
        writeln!(out, "  private let ownsHandle: Bool").unwrap();
        writeln!(out, "  private var disposed = false").unwrap();
        writeln!(out).unwrap();
        writeln!(
            out,
            "  public init(nativeHandle: {handle_type}, ownsHandle: Bool = true) {{"
        )
        .unwrap();
        writeln!(out, "    self.nativeHandle = nativeHandle").unwrap();
        writeln!(out, "    self.ownsHandle = ownsHandle").unwrap();
        writeln!(out, "  }}").unwrap();
        writeln!(out).unwrap();
        writeln!(out, "  deinit {{").unwrap();
        writeln!(out, "    guard ownsHandle, !disposed else {{ return }}").unwrap();
        writeln!(
            out,
            "    native_handle_finalize(UnsafeMutableRawPointer(bitPattern: UInt(nativeHandle)))"
        )
        .unwrap();
        writeln!(out, "  }}").unwrap();
        writeln!(out).unwrap();
        writeln!(
            out,
            "  /// Releases this reference now; call on the UI thread."
        )
        .unwrap();
        writeln!(out, "  public func dispose() {{").unwrap();
        writeln!(out, "    guard ownsHandle, !disposed else {{ return }}").unwrap();
        writeln!(out, "    disposed = true").unwrap();
        writeln!(out, "    releaseNativeHandle()").unwrap();
        writeln!(out, "  }}").unwrap();
        writeln!(out).unwrap();
        writeln!(
            out,
            "  /// Releases this reference with its own C ABI function."
        )
        .unwrap();
        writeln!(out, "  public func releaseNativeHandle() {{").unwrap();
        writeln!(out, "    {free}(nativeHandle)").unwrap();
        writeln!(out, "  }}").unwrap();
        writeln!(out).unwrap();
    }

    for ctor in &class.constructors {
        generate_swift_constructor(out, api, class, ctor, prefix);
    }

    for method in &class.methods {
        let receiver =
            (class.is_instance() && !method.is_static).then(|| "nativeHandle".to_string());
        generate_swift_method(out, api, class, method, prefix, "  ", receiver);
    }

    if class.native_object {
        writeln!(
            out,
            "  /// Platform-specific native object behind this handle."
        )
        .unwrap();
        writeln!(
            out,
            "  public var nativeObject: UnsafeMutableRawPointer? {{"
        )
        .unwrap();
        writeln!(
            out,
            "    {}(nativeHandle)",
            c_native_object_symbol(prefix, &class.name)
        )
        .unwrap();
        writeln!(out, "  }}").unwrap();
        writeln!(out).unwrap();
    }

    generate_swift_listener(out, api, class, prefix, "  ");

    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn generate_swift_constructor(
    out: &mut String,
    api: &Api,
    class: &Class,
    ctor: &Constructor,
    prefix: &str,
) {
    let label = match constructor_suffix(class, ctor) {
        Some(suffix) => format!("create{}", suffix.to_upper_camel_case()),
        None => "create".to_string(),
    };
    writeln!(
        out,
        "  /// Creates a new `{}`; returns nil if the native side failed.",
        class.name
    )
    .unwrap();
    writeln!(
        out,
        "  public {}class func {label}({}) -> {}? {{",
        if constructor_overrides(api, class, ctor) {
            "override "
        } else {
            ""
        },
        swift_params(&ctor.params),
        class.name
    )
    .unwrap();
    render_param_bindings(out, api, &ctor.params, prefix, "    ");
    writeln!(
        out,
        "    let handle = {}({})",
        c_constructor_symbol(prefix, class, ctor),
        call_args(&ctor.params, None)
    )
    .unwrap();
    writeln!(
        out,
        "    guard handle != {} else {{ return nil }}",
        c_invalid_handle_macro(prefix, &class.name)
    )
    .unwrap();
    writeln!(out, "    return {}(nativeHandle: handle)", class.name).unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out).unwrap();
}

fn generate_swift_method(
    out: &mut String,
    api: &Api,
    class: &Class,
    method: &Method,
    prefix: &str,
    indent: &str,
    receiver: Option<String>,
) {
    let shape = method_shape(class, method);
    let declaration = method_declaration(class, method, &shape);
    let body_indent = format!("{indent}  ");

    writeln!(out, "{indent}public {declaration} {{").unwrap();
    render_param_bindings(out, api, &method.params, prefix, &body_indent);

    let symbol = c_method_symbol(prefix, class, method);
    let args = call_args(&method.params, receiver);
    render_return(
        out,
        &method.return_type,
        &symbol,
        &args,
        api,
        prefix,
        &body_indent,
    );

    writeln!(out, "{indent}}}").unwrap();
    writeln!(out).unwrap();
}

fn generate_swift_listener(out: &mut String, api: &Api, class: &Class, prefix: &str, indent: &str) {
    let Some(group) = emitted_group(api, class) else {
        return;
    };
    let raw_ty = c_type_name(prefix, &group.name);
    let self_arg = if class.is_instance() {
        "nativeHandle, "
    } else {
        ""
    };

    writeln!(
        out,
        "{indent}/// Registers `callback` for every `{}` this `{}` emits.",
        group.name, class.name
    )
    .unwrap();
    writeln!(out, "{indent}///").unwrap();
    writeln!(
        out,
        "{indent}/// The closure runs synchronously on the UI thread; the context is"
    )
    .unwrap();
    writeln!(
        out,
        "{indent}/// released through the C ABI when the listener is removed."
    )
    .unwrap();
    writeln!(
        out,
        "{indent}@discardableResult public func addListener(_ callback: @escaping ({}) -> Void) -> ListenerId {{",
        group.name
    )
    .unwrap();
    writeln!(
        out,
        "{indent}  let context = Unmanaged.passRetained(CallbackBox1<{}>(callback)).toOpaque()",
        group.name
    )
    .unwrap();
    writeln!(
        out,
        "{indent}  let trampoline: @convention(c) (UnsafePointer<{raw_ty}>?, UnsafeMutableRawPointer?) -> Void = {{ event, userData in"
    )
    .unwrap();
    writeln!(
        out,
        "{indent}    guard let event, let userData, let value = {}(raw: event.pointee) else {{ return }}",
        group.name
    )
    .unwrap();
    writeln!(
        out,
        "{indent}    Unmanaged<CallbackBox1<{}>>.fromOpaque(userData).takeUnretainedValue().body(value)",
        group.name
    )
    .unwrap();
    writeln!(out, "{indent}  }}").unwrap();
    writeln!(
        out,
        "{indent}  return {}({self_arg}trampoline, context, nativeapiReleaseUserData)",
        c_add_listener_symbol(prefix, &class.name)
    )
    .unwrap();
    writeln!(out, "{indent}}}").unwrap();
    writeln!(out).unwrap();

    writeln!(
        out,
        "{indent}/// Unregisters a listener. Returns false if unknown."
    )
    .unwrap();
    writeln!(
        out,
        "{indent}public func removeListener(_ listenerId: ListenerId) -> Bool {{"
    )
    .unwrap();
    writeln!(
        out,
        "{indent}  {}({self_arg}listenerId)",
        c_remove_listener_symbol(prefix, &class.name)
    )
    .unwrap();
    writeln!(out, "{indent}}}").unwrap();
    writeln!(out).unwrap();
}

fn emitted_group<'a>(api: &'a Api, class: &Class) -> Option<&'a EventGroup> {
    let event = class.event.as_ref()?;
    api.headers
        .iter()
        .flat_map(|header| header.events.iter())
        .find(|group| &group.name == event)
}

// ---------------------------------------------------------------------------
// Parameters and returns
// ---------------------------------------------------------------------------

fn swift_params(params: &[Param]) -> String {
    params
        .iter()
        .enumerate()
        .map(|(index, param)| {
            let name = swift_ident(&param.name.to_lower_camel_case());
            if index == 0 {
                format!("_ {name}: {}", swift_param_type(&param.ty))
            } else {
                // The label and the local name are the same, so Swift's short
                // form (`animate: Bool`) applies.
                format!("{name}: {}", swift_param_type(&param.ty))
            }
        })
        .collect::<Vec<_>>()
        .join(", ")
}

fn swift_param_type(ty: &TypeRef) -> String {
    match ty {
        TypeRef::String | TypeRef::CString => "String".to_string(),
        TypeRef::Object {
            name, shared: true, ..
        } => format!("{name}?"),
        TypeRef::Object { name, .. } => name.clone(),
        TypeRef::Vector { element } if matches!(element.as_ref(), TypeRef::String) => {
            "[String]".to_string()
        }
        TypeRef::Map { .. } => "[String: String]".to_string(),
        TypeRef::Callback { params } => {
            format!("@escaping ({}) -> Void", swift_callback_args(params))
        }
        TypeRef::Optional { inner } => match inner.as_ref() {
            TypeRef::Callback { params } => {
                format!("(({}) -> Void)?", swift_callback_args(params))
            }
            other => match swift_param_type(other) {
                base if base.ends_with('?') => base,
                base => format!("{base}?"),
            },
        },
        other => swift_public_type(other),
    }
}

fn swift_callback_args(params: &[TypeRef]) -> String {
    params
        .iter()
        .map(swift_public_type)
        .collect::<Vec<_>>()
        .join(", ")
}

/// Locals the call needs: C strings, converted structs, retained closures.
fn render_param_bindings(
    out: &mut String,
    api: &Api,
    params: &[Param],
    prefix: &str,
    indent: &str,
) {
    for param in params {
        let name = swift_ident(&param.name.to_lower_camel_case());
        match &param.ty {
            TypeRef::String | TypeRef::CString => {
                writeln!(out, "{indent}let {name}CString = strdup({name})").unwrap();
                writeln!(out, "{indent}defer {{ free({name}CString) }}").unwrap();
            }
            TypeRef::Struct {
                name: type_name, ..
            } => {
                if struct_allocates_named(api, type_name) {
                    writeln!(out, "{indent}var {name}Raw = {name}.toRaw()").unwrap();
                    writeln!(
                        out,
                        "{indent}defer {{ {type_name}.releaseRaw(&{name}Raw) }}"
                    )
                    .unwrap();
                } else {
                    writeln!(out, "{indent}let {name}Raw = {name}.toRaw()").unwrap();
                }
            }
            TypeRef::Vector { element } if matches!(element.as_ref(), TypeRef::String) => {
                writeln!(
                    out,
                    "{indent}let {name}Pointers = {name}.map {{ strdup($0) }}"
                )
                .unwrap();
                writeln!(
                    out,
                    "{indent}defer {{ {name}Pointers.forEach {{ free($0) }} }}"
                )
                .unwrap();
                writeln!(out, "{indent}var {name}List = native_string_list_t()").unwrap();
                writeln!(out, "{indent}{name}List.count = numericCast({name}Pointers.count)").unwrap();
                writeln!(out, "{indent}if !{name}Pointers.isEmpty {{").unwrap();
                writeln!(
                    out,
                    "{indent}  {name}List.items = UnsafeMutablePointer<UnsafeMutablePointer<CChar>?>.allocate(capacity: {name}Pointers.count)"
                )
                .unwrap();
                writeln!(
                    out,
                    "{indent}  for (index, pointer) in {name}Pointers.enumerated() {{ {name}List.items[index] = pointer }}"
                )
                .unwrap();
                writeln!(out, "{indent}}}").unwrap();
                writeln!(out, "{indent}defer {{ {name}List.items?.deallocate() }}").unwrap();
            }
            TypeRef::Map { .. } => {
                writeln!(
                    out,
                    "{indent}let {name}Keys = {name}.keys.map {{ strdup($0) }}"
                )
                .unwrap();
                writeln!(
                    out,
                    "{indent}let {name}Values = {name}.values.map {{ strdup($0) }}"
                )
                .unwrap();
                writeln!(
                    out,
                    "{indent}defer {{ {name}Keys.forEach {{ free($0) }}; {name}Values.forEach {{ free($0) }} }}"
                )
                .unwrap();
                writeln!(out, "{indent}var {name}Map = native_string_map_t()").unwrap();
                writeln!(out, "{indent}{name}Map.count = numericCast({name}Keys.count)").unwrap();
                writeln!(out, "{indent}if !{name}Keys.isEmpty {{").unwrap();
                writeln!(
                    out,
                    "{indent}  {name}Map.keys = UnsafeMutablePointer<UnsafeMutablePointer<CChar>?>.allocate(capacity: {name}Keys.count)"
                )
                .unwrap();
                writeln!(
                    out,
                    "{indent}  {name}Map.values = UnsafeMutablePointer<UnsafeMutablePointer<CChar>?>.allocate(capacity: {name}Values.count)"
                )
                .unwrap();
                writeln!(
                    out,
                    "{indent}  for (index, pointer) in {name}Keys.enumerated() {{ {name}Map.keys[index] = pointer }}"
                )
                .unwrap();
                writeln!(
                    out,
                    "{indent}  for (index, pointer) in {name}Values.enumerated() {{ {name}Map.values[index] = pointer }}"
                )
                .unwrap();
                writeln!(out, "{indent}}}").unwrap();
                writeln!(
                    out,
                    "{indent}defer {{ {name}Map.keys?.deallocate(); {name}Map.values?.deallocate() }}"
                )
                .unwrap();
            }
            TypeRef::Callback { params: args } => {
                render_callback_parameter(out, &name, args, indent);
            }
            TypeRef::Optional { inner } => match inner.as_ref() {
                TypeRef::String | TypeRef::CString => {
                    writeln!(
                        out,
                        "{indent}let {name}CString = {name}.map {{ strdup($0) }} ?? nil"
                    )
                    .unwrap();
                    writeln!(out, "{indent}defer {{ free({name}CString) }}").unwrap();
                }
                TypeRef::Struct {
                    name: type_name, ..
                } => {
                    // `&someOptional` would hand C a pointer to the Optional
                    // itself, so the payload gets its own allocation instead.
                    let c_ty = c_type_name(prefix, type_name);
                    writeln!(
                        out,
                        "{indent}let {name}Pointer = {name}.map {{ value -> UnsafeMutablePointer<{c_ty}> in"
                    )
                    .unwrap();
                    writeln!(
                        out,
                        "{indent}  let pointer = UnsafeMutablePointer<{c_ty}>.allocate(capacity: 1)"
                    )
                    .unwrap();
                    writeln!(out, "{indent}  pointer.initialize(to: value.toRaw())").unwrap();
                    writeln!(out, "{indent}  return pointer").unwrap();
                    writeln!(out, "{indent}}}").unwrap();
                    writeln!(out, "{indent}defer {{").unwrap();
                    writeln!(out, "{indent}  if let pointer = {name}Pointer {{").unwrap();
                    if struct_allocates_named(api, type_name) {
                        writeln!(out, "{indent}    {type_name}.releaseRaw(&pointer.pointee)")
                            .unwrap();
                    }
                    writeln!(out, "{indent}    pointer.deinitialize(count: 1)").unwrap();
                    writeln!(out, "{indent}    pointer.deallocate()").unwrap();
                    writeln!(out, "{indent}  }}").unwrap();
                    writeln!(out, "{indent}}}").unwrap();
                }
                TypeRef::Callback { params: args } => {
                    render_optional_callback_parameter(out, &name, args, indent);
                }
                _ => {}
            },
            _ => {}
        }
    }
}

fn render_callback_parameter(out: &mut String, name: &str, params: &[TypeRef], indent: &str) {
    let arity = params.len();
    let generics = swift_box_generics(params);
    writeln!(
        out,
        "{indent}let {name}Context = Unmanaged.passRetained(CallbackBox{arity}{generics}({name})).toOpaque()"
    )
    .unwrap();
    render_callback_trampoline(out, name, params, indent);
}

fn render_optional_callback_parameter(
    out: &mut String,
    name: &str,
    params: &[TypeRef],
    indent: &str,
) {
    let arity = params.len();
    let generics = swift_box_generics(params);
    writeln!(
        out,
        "{indent}let {name}Context = {name}.map {{ Unmanaged.passRetained(CallbackBox{arity}{generics}($0)).toOpaque() }}"
    )
    .unwrap();
    render_callback_trampoline(out, name, params, indent);
}

fn render_callback_trampoline(out: &mut String, name: &str, params: &[TypeRef], indent: &str) {
    let arity = params.len();
    let generics = swift_box_generics(params);
    let delivery = callback_needs_delivery(params);
    let mut c_types: Vec<String> = params.iter().map(swift_c_callback_arg_type).collect();
    let mut c_names: Vec<String> = (0..arity).map(|index| format!("arg{index}")).collect();
    if delivery {
        c_types.push("native_event_delivery_t".to_string());
        c_names.push("delivery".to_string());
    }
    c_types.push("UnsafeMutableRawPointer?".to_string());
    c_names.push("userData".to_string());

    writeln!(
        out,
        "{indent}let {name}Trampoline: @convention(c) ({}) -> Void = {{ {} in",
        c_types.join(", "),
        c_names.join(", ")
    )
    .unwrap();
    let inner = format!("{indent}  ");
    if delivery {
        writeln!(
            out,
            "{inner}defer {{ _ = native_event_delivery_complete(delivery, true) }}"
        )
        .unwrap();
    }
    writeln!(out, "{inner}guard let userData else {{ return }}").unwrap();

    let mut values: Vec<String> = Vec::new();
    for (index, ty) in params.iter().enumerate() {
        let arg = format!("arg{index}");
        let (statements, value) = swift_callback_arg_value(ty, &arg);
        if let Some(statement) = statements {
            writeln!(out, "{inner}{statement}").unwrap();
        }
        values.push(value);
    }
    writeln!(
        out,
        "{inner}Unmanaged<CallbackBox{arity}{generics}>.fromOpaque(userData).takeUnretainedValue().body({})",
        values.join(", ")
    )
    .unwrap();
    writeln!(out, "{indent}}}").unwrap();
}

fn swift_callback_arg_value(ty: &TypeRef, arg: &str) -> (Option<String>, String) {
    match ty {
        TypeRef::String | TypeRef::CString | TypeRef::Optional { .. } => match ty.unwrap_optional()
        {
            TypeRef::String | TypeRef::CString => {
                (None, format!("{arg}.map {{ String(cString: $0) }}"))
            }
            TypeRef::Struct { name, .. } => {
                (None, format!("{arg}.map {{ {name}(raw: $0.pointee) }}"))
            }
            TypeRef::Object { name, .. } => (
                None,
                format!("nativeapiOwned({arg}) {{ {name}(nativeHandle: $0) }}"),
            ),
            TypeRef::Enum { name, .. } => (None, format!("{name}(raw: {arg})")),
            _other => (None, arg.to_string()),
        },
        TypeRef::Struct { name, .. } => (
            Some(format!("guard let value = {arg} else {{ return }}")),
            format!("{name}(raw: value.pointee)"),
        ),
        TypeRef::Vector { element } if matches!(element.as_ref(), TypeRef::String) => (
            Some(format!("guard let value = {arg} else {{ return }}")),
            "nativeapiStringList(value.pointee)".to_string(),
        ),
        TypeRef::Map { .. } => (
            Some(format!("guard let value = {arg} else {{ return }}")),
            "nativeapiStringMap(value.pointee)".to_string(),
        ),
        TypeRef::Object { name, .. } => (
            None,
            format!("nativeapiOwned({arg}) {{ {name}(nativeHandle: $0) }}"),
        ),
        TypeRef::Enum { name, .. } => (None, format!("{name}(raw: {arg})")),
        TypeRef::Alias { underlying, .. } => swift_callback_arg_value(underlying, arg),
        _ => (None, arg.to_string()),
    }
}

fn swift_c_callback_arg_type(ty: &TypeRef) -> String {
    match ty.unwrap_optional() {
        TypeRef::String | TypeRef::CString => "UnsafePointer<CChar>?".to_string(),
        TypeRef::Struct { name, .. } => format!("UnsafePointer<{}>?", c_type_name(PREFIX, name)),
        TypeRef::Vector { element } if matches!(element.as_ref(), TypeRef::String) => {
            format!("UnsafePointer<{STRING_LIST_TYPE}>?")
        }
        TypeRef::Map { .. } => format!("UnsafePointer<{STRING_MAP_TYPE}>?"),
        TypeRef::Object { name, .. } => c_type_name(PREFIX, name),
        TypeRef::Enum { name, .. } => c_type_name(PREFIX, name),
        TypeRef::Alias { underlying, .. } => swift_c_callback_arg_type(underlying),
        TypeRef::Bool => "Bool".to_string(),
        TypeRef::Int { name } => swift_int_type(name),
        TypeRef::Float { name } => swift_float_type(name),
        TypeRef::RawPointer => "UnsafeMutableRawPointer?".to_string(),
        other => swift_public_type(other),
    }
}

/// Callbacks that carry a payload borrow it until they acknowledge delivery.
/// Scalar-only callbacks (hooks, shortcut activation) have no delivery token.
fn callback_needs_delivery(params: &[TypeRef]) -> bool {
    params.iter().any(|param| {
        matches!(
            param.unwrap_optional(),
            TypeRef::String
                | TypeRef::CString
                | TypeRef::Struct { .. }
                | TypeRef::Object { .. }
                | TypeRef::Vector { .. }
                | TypeRef::Map { .. }
        )
    })
}

fn swift_box_generics(params: &[TypeRef]) -> String {
    if params.is_empty() {
        String::new()
    } else {
        format!(
            "<{}>",
            params
                .iter()
                .map(swift_public_type)
                .collect::<Vec<_>>()
                .join(", ")
        )
    }
}

fn call_args(params: &[Param], receiver: Option<String>) -> String {
    let mut args: Vec<String> = receiver.into_iter().collect();
    for param in params {
        let name = swift_ident(&param.name.to_lower_camel_case());
        match &param.ty {
            TypeRef::String | TypeRef::CString => args.push(format!("{name}CString")),
            TypeRef::Object { shared: true, .. } => args.push(format!("{name}?.nativeHandle ?? 0")),
            TypeRef::Object { .. } => args.push(format!("{name}.nativeHandle")),
            TypeRef::Struct { .. } => args.push(format!("{name}Raw")),
            TypeRef::Enum { .. } => args.push(format!("{name}.raw")),
            TypeRef::Vector { .. } => args.push(format!("{name}List")),
            TypeRef::Map { .. } => args.push(format!("{name}Map")),
            TypeRef::Callback { .. } => {
                args.push(format!("{name}Trampoline"));
                args.push(format!("{name}Context"));
                args.push("nativeapiReleaseUserData".to_string());
            }
            TypeRef::Optional { inner } => match inner.as_ref() {
                TypeRef::String | TypeRef::CString => args.push(format!("{name}CString")),
                TypeRef::Object { .. } => args.push(format!("{name}?.nativeHandle ?? 0")),
                TypeRef::Struct { .. } => args.push(format!("{name}Pointer")),
                TypeRef::Callback { .. } => {
                    args.push(format!("{name}Context != nil ? {name}Trampoline : nil"));
                    args.push(format!("{name}Context"));
                    args.push("nativeapiReleaseUserData".to_string());
                }
                _ => args.push(name),
            },
            _ => args.push(name),
        }
    }
    args.join(", ")
}

fn render_return(
    out: &mut String,
    ty: &TypeRef,
    symbol: &str,
    args: &str,
    api: &Api,
    prefix: &str,
    indent: &str,
) {
    match ty {
        TypeRef::Void => {
            writeln!(out, "{indent}{symbol}({args})").unwrap();
        }
        TypeRef::String | TypeRef::CString => {
            writeln!(
                out,
                "{indent}guard let value = {symbol}({args}) else {{ return nil }}"
            )
            .unwrap();
            writeln!(out, "{indent}defer {{ {STRING_FREE_FN}(value) }}").unwrap();
            writeln!(out, "{indent}return String(cString: value)").unwrap();
        }
        TypeRef::Struct { name, .. } => {
            if struct_owns_memory(api, name) {
                writeln!(out, "{indent}var raw = {symbol}({args})").unwrap();
                writeln!(out, "{indent}let result = {name}(raw: raw)").unwrap();
                writeln!(out, "{indent}{}(&raw)", c_free_symbol(prefix, name)).unwrap();
                writeln!(out, "{indent}return result").unwrap();
            } else {
                writeln!(out, "{indent}return {name}(raw: {symbol}({args}))").unwrap();
            }
        }
        TypeRef::Enum { name, .. } => {
            writeln!(out, "{indent}return {name}(raw: {symbol}({args}))").unwrap();
        }
        TypeRef::Object { name, .. } => {
            writeln!(out, "{indent}let handle = {symbol}({args})").unwrap();
            writeln!(
                out,
                "{indent}guard handle != {} else {{ return nil }}",
                c_invalid_handle_macro(prefix, name)
            )
            .unwrap();
            writeln!(out, "{indent}return {name}(nativeHandle: handle)").unwrap();
        }
        TypeRef::Vector { element } if matches!(element.as_ref(), TypeRef::String) => {
            writeln!(out, "{indent}var list = {symbol}({args})").unwrap();
            writeln!(out, "{indent}let items = nativeapiStringList(list)").unwrap();
            writeln!(out, "{indent}{STRING_LIST_FREE_FN}(&list)").unwrap();
            writeln!(out, "{indent}return items").unwrap();
        }
        TypeRef::Vector { element } => {
            generate_swift_list_return(out, element, prefix, symbol, args, indent);
        }
        TypeRef::Map { .. } => {
            writeln!(out, "{indent}var raw = {symbol}({args})").unwrap();
            writeln!(out, "{indent}let entries = nativeapiStringMap(raw)").unwrap();
            writeln!(out, "{indent}{STRING_MAP_FREE_FN}(&raw)").unwrap();
            writeln!(out, "{indent}return entries").unwrap();
        }
        TypeRef::Optional { inner } => render_return(out, inner, symbol, args, api, prefix, indent),
        TypeRef::Alias { underlying, .. } => {
            render_return(out, underlying, symbol, args, api, prefix, indent)
        }
        TypeRef::Callback { .. } => {
            writeln!(out, "{indent}{symbol}({args})").unwrap();
        }
        _ => {
            writeln!(out, "{indent}return {symbol}({args})").unwrap();
        }
    }
}

fn generate_swift_list_return(
    out: &mut String,
    element: &TypeRef,
    prefix: &str,
    symbol: &str,
    args: &str,
    indent: &str,
) {
    let name = match element {
        TypeRef::Object { name, .. } => name,
        _ => return,
    };
    let field = c_list_field(name);
    let invalid = c_invalid_handle_macro(prefix, name);
    writeln!(out, "{indent}var list = {symbol}({args})").unwrap();
    writeln!(out, "{indent}var items: [{name}] = []").unwrap();
    writeln!(out, "{indent}if let buffer = list.{field} {{").unwrap();
    writeln!(out, "{indent}  for index in 0..<Int(list.count) {{").unwrap();
    writeln!(out, "{indent}    let handle = buffer[index]").unwrap();
    writeln!(out, "{indent}    if handle != {invalid} {{").unwrap();
    writeln!(
        out,
        "{indent}      items.append({name}(nativeHandle: handle))"
    )
    .unwrap();
    writeln!(out, "{indent}    }}").unwrap();
    writeln!(out, "{indent}  }}").unwrap();
    writeln!(out, "{indent}}}").unwrap();
    writeln!(
        out,
        "{indent}// The handles now belong to `items`; free just the array."
    )
    .unwrap();
    writeln!(
        out,
        "{indent}{}(&list)",
        c_list_release_symbol(prefix, name)
    )
    .unwrap();
    writeln!(out, "{indent}return items").unwrap();
}

